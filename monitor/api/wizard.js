// Creates and runs a sync between two saved SQL Server connections using SymmetricDS:
//   write engine files (picked up by the sym-runtime supervisor) -> load generated config into the source DB -> target registers -> initial load.
import fs from 'node:fs';
import path from 'node:path';
import { q, exec, testConnection, cfgFor, explain, dropPool } from './db.js';
import { getPair, savePair, listPairs, getConnection } from './store.js';
import { compareSchema, createTableSql, tableColumns, loadOrder, userTriggers, spatialColumns, fq } from './discovery.js';
import { computeParity } from './parity.js';
import { analyzeDependencies, markExisting, targetFkProblems } from './dependencies.js';

const ENG_DIR = process.env.RUNTIME_ENGINES_DIR || '/runtime/engines';
const SYNC_HOST = process.env.RUNTIME_SYNC_HOST || 'sym-runtime';
const esc = (s) => String(s).replace(/'/g, "''");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const running = new Set();                              // pair ids with an apply in progress

export const engineNames = (p) => ({ src: `src-${p.id}`, tgt: `tgt-${p.id}` });
export const nodeIds = (p) => ({ src: `${p.id}-s`, tgt: `${p.id}-t` });

// ---------- engine files ----------
const propEscape = (v) => String(v).replace(/\\/g, '\\\\').replace(/[^\x20-\x7e]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0')).replace(/^ /, '\\ ');
function engineProps(pair, role) {
  const cid = role === 'src' ? pair.sourceConnId : pair.targetConnId;
  const c = cfgFor(cid); const n = engineNames(pair); const ids = nodeIds(pair);
  const url = `jdbc:sqlserver://${c.host}:${c.port};databaseName=${c.database};encrypt=${c.encrypt !== false};trustServerCertificate=${c.trustCert !== false};loginTimeout=15`;
  const lines = [
    `# generated by the monitor UI for sync "${pair.name}" - do not edit`,
    `engine.name=${n[role]}`, `group.id=${role === 'src' ? 'source' : 'target'}`, `external.id=${ids[role]}`,
    'db.driver=com.microsoft.sqlserver.jdbc.SQLServerDriver', `db.url=${propEscape(url)}`, `db.user=${propEscape(c.user)}`, `db.password=${propEscape(c.password)}`,
    role === 'src' ? 'registration.url=' : `registration.url=http://localhost:31415/sync/${n.src}`,
    `sync.url=http://${SYNC_HOST}:31415/sync/${n[role]}`,
    'auto.config.database=true',
    // keep non-Latin text (Japanese, Cyrillic, emoji ...) intact: sym_data captures nvarchar data as ntext instead of varchar.
    // Must be on BEFORE the sym_ tables are created, it does not repair an existing install.
    'mssql.use.ntypes.for.sync=true',
    ...(role === 'src' ? ['auto.reload=true', 'auto.registration=true'] : []),
    'job.routing.period.time.ms=2000', 'job.push.period.time.ms=2000', 'job.pull.period.time.ms=2000',
  ];
  return lines.join('\n') + '\n';
}
const engineFile = (pair, role) => path.join(ENG_DIR, `${engineNames(pair)[role]}.properties`);
function writeEngine(pair, role) {
  fs.mkdirSync(ENG_DIR, { recursive: true });
  const f = engineFile(pair, role); const t = f + '.tmp';
  fs.writeFileSync(t, engineProps(pair, role), { mode: 0o666 }); fs.renameSync(t, f);   // supervisor only reads *.properties
}
const removeEngine = (pair, role) => { try { fs.unlinkSync(engineFile(pair, role)); } catch { /* already gone */ } };
export const engineFilesPresent = (pair) => ({ src: fs.existsSync(engineFile(pair, 'src')), tgt: fs.existsSync(engineFile(pair, 'tgt')) });

// ---------- step runner ----------
async function step(pair, name, fn) {
  const s = { name, status: 'running', detail: '', at: new Date().toISOString() };
  pair.steps.push(s); savePair(pair);
  try {
    const r = await fn(s);
    s.status = r?.skipped ? 'skipped' : 'ok'; s.detail = (typeof r === 'string' ? r : r?.detail) ?? s.detail; s.doneAt = new Date().toISOString();
    savePair(pair);
  } catch (e) {
    s.status = 'error'; s.detail = explain(e); s.doneAt = new Date().toISOString();
    pair.state = 'error'; pair.error = `${name}: ${s.detail}`; savePair(pair);
    throw e;
  }
}
const note = (pair, s, text) => { s.detail = text; savePair(pair); };
async function waitFor(fn, { timeout = 180000, every = 2000, what = 'condition' } = {}) {
  const end = Date.now() + timeout; let last;
  while (Date.now() < end) { try { const v = await fn(); if (v) return v; } catch (e) { last = e; } await sleep(every); }
  throw new Error(`Timed out waiting for ${what}${last ? ` (last error: ${explain(last)})` : ''}`);
}

// ---------- config written into the source database ----------
function configSql(pair, ordered, excluded = {}) {
  const out = ['SET NOCOUNT ON;',
    `DELETE FROM sym_trigger_router WHERE router_id = 'sync_router';`,
    `DELETE FROM sym_trigger WHERE trigger_id LIKE 'sync[_]%';`,
    `DELETE FROM sym_router WHERE router_id = 'sync_router';`,
    `DELETE FROM sym_node_group_link WHERE source_node_group_id = 'source' AND target_node_group_id = 'target';`,
    `DELETE FROM sym_channel WHERE channel_id = 'sync_data';`,
    `IF NOT EXISTS (SELECT 1 FROM sym_node_group WHERE node_group_id = 'source') INSERT INTO sym_node_group (node_group_id, description) VALUES ('source', 'source');`,
    `IF NOT EXISTS (SELECT 1 FROM sym_node_group WHERE node_group_id = 'target') INSERT INTO sym_node_group (node_group_id, description) VALUES ('target', 'target');`,
    `INSERT INTO sym_node_group_link (source_node_group_id, target_node_group_id, data_event_action) VALUES ('source', 'target', 'P');`,
    // one ordered channel keeps parent/child rows in commit order across tables
    `INSERT INTO sym_channel (channel_id, processing_order, max_batch_size, max_batch_to_send, enabled, description) VALUES ('sync_data', 10, 1000, 20, 1, 'tables selected in the monitor UI');`,
    `INSERT INTO sym_router (router_id, source_node_group_id, target_node_group_id, router_type, create_time, last_update_time) VALUES ('sync_router', 'source', 'target', 'default', GETDATE(), GETDATE());`];
  ordered.forEach((t, i) => {
    const [schema, ...rest] = t.split('.'); const table = rest.join('.'); const tid = `sync_${schema}_${table}`.slice(0, 120);
    const ex = (excluded[t] || []).join(',');
    out.push(`INSERT INTO sym_trigger (trigger_id, source_schema_name, source_table_name, channel_id, excluded_column_names, last_update_time, create_time) VALUES ('${esc(tid)}', '${esc(schema)}', '${esc(table)}', 'sync_data', ${ex ? `'${esc(ex)}'` : 'NULL'}, GETDATE(), GETDATE());`);
    out.push(`INSERT INTO sym_trigger_router (trigger_id, router_id, initial_load_order, last_update_time, create_time) VALUES ('${esc(tid)}', 'sync_router', ${(i + 1) * 10}, GETDATE(), GETDATE());`);
  });
  return out.join('\n');
}
const captureTriggerCount = async (cid, tables) => {
  let n = 0;
  for (const t of tables) { const [s, ...r] = t.split('.'); n += (await q(cid, `SELECT COUNT(*) AS n FROM sys.triggers WHERE name LIKE 'SYM[_]ON[_]%' AND parent_id = OBJECT_ID(@t)`, { t: fq(s, r.join('.')) }))[0].n; }
  return n;
};

// ---------- validation shared by "check" and "apply" ----------
export async function precheck(input, selfId = null) {
  const problems = []; const warnings = [];
  const sc = getConnection(input.sourceConnId); const tc = getConnection(input.targetConnId);
  if (!sc || !tc) return { ok: false, problems: ['Choose a source and a target connection'], warnings };
  if (sc.id === tc.id) problems.push('Source and target must be different connections');
  if (sc.host.toLowerCase() === tc.host.toLowerCase() && sc.port === tc.port && sc.database.toLowerCase() === tc.database.toLowerCase()) problems.push('Source and target point at the same database');
  for (const p of listPairs()) {
    if (p.id === selfId || p.system || p.state === 'removed') continue;
    if ([p.sourceConnId, p.targetConnId].some((x) => [sc.id, tc.id].includes(x))) problems.push(`A connection is already used by the sync "${p.name}". Use a different database or remove that sync first`);
  }
  const [a, b] = await Promise.all([testConnection(cfgFor(sc.id)), testConnection(cfgFor(tc.id))]);
  if (!a.ok) problems.push(`Source: ${a.error}`); else problems.push(...a.problems.map((x) => `Source: ${x}`));
  if (!b.ok) problems.push(`Target: ${b.error}`); else problems.push(...b.problems.map((x) => `Target: ${x}`));
  if (a.ok && b.ok) {
    if (a.sqlMajor && a.sqlMajor < 11) problems.push('Source SQL Server version is too old (2012 or newer is required)');
    if (b.sqlMajor && b.sqlMajor < 11) problems.push('Target SQL Server version is too old (2012 or newer is required)');
    if (a.hasSymTables && !(selfId && getPair(selfId))) problems.push('Source database already contains SymmetricDS tables (sym_*) from another installation. Remove them or use another database');
    if (b.hasSymTables && !(selfId && getPair(selfId))) problems.push('Target database already contains SymmetricDS tables (sym_*) from another installation. Remove them or use another database');
    if (!a.rcsi) warnings.push('Source database does not use READ_COMMITTED_SNAPSHOT: SymmetricDS triggers can block writers a little more (optional setting in step 4)');
  }
  return { ok: problems.length === 0, problems, warnings, source: a, target: b };
}

// ---------- apply ----------
export function startApply(pair, user) {
  if (running.has(pair.id)) throw Object.assign(new Error('An apply is already running for this sync'), { statusCode: 409 });
  running.add(pair.id);
  pair.state = 'applying'; pair.error = null; pair.steps = []; pair.applyStartedAt = new Date().toISOString(); savePair(pair);
  applyPair(pair, user).catch(() => {}).finally(() => running.delete(pair.id));
}

async function applyPair(pair, user) {
  const src = pair.sourceConnId, tgt = pair.targetConnId, ids = nodeIds(pair);
  try {
    await step(pair, 'Check connections', async () => {
      const r = await precheck(pair, pair.id);
      if (!r.ok) throw new Error(r.problems.join(' | '));
      return `Source ${r.source.version} / target ${r.target.version}`;
    });

    let ordered;
    await step(pair, 'Check tables and target schema', async (s) => {
      const tables = pair.tables;
      if (!tables.length) throw new Error('No tables selected');
      ordered = await loadOrder(src, tables);
      pair.excluded = {};
      for (const t of ordered) { const [sch, ...r] = t.split('.'); const sp = await spatialColumns(src, sch, r.join('.')); if (sp.length) pair.excluded[t] = sp; }
      const cmp = await compareSchema(src, tgt, ordered);
      const bad = cmp.filter((c) => c.status === 'mismatch');
      if (bad.length) throw new Error('Target tables differ from the source: ' + bad.map((c) => `${c.table} (${[c.missingCols?.length ? 'missing columns ' + c.missingCols.join(', ') : '', ...(c.typeDiff || [])].filter(Boolean).join('; ')})`).join(' | ') + '. Fix the target tables, or drop them and let the wizard create them.');
      const missing = cmp.filter((c) => c.status === 'missing');
      pair.ddl = Object.fromEntries(missing.map((c) => [c.table, c.ddl])); savePair(pair);
      if (missing.length && !pair.options.createMissing) throw new Error(`These tables do not exist on the target: ${missing.map((m) => m.table).join(', ')}. Tick "Create missing tables on the target" or create them yourself.`);
      // dependencies: objects (functions, alias types, sequences) needed by the tables we will create, and foreign keys
      const deps = await analyzeDependencies(src, ordered, { objectTables: missing.map((m) => m.table) });
      if (deps.blockers.length) throw new Error('Dependencies that cannot be copied automatically: ' + deps.blockers.join(' | '));
      const fkProblems = await targetFkProblems(tgt, ordered);
      if (fkProblems.length) throw new Error('Foreign key dependencies: ' + fkProblems.join(' | ') + '. Add the parent table(s) to the sync (step 2 offers "Add required parent tables") or disable/drop those foreign keys on the target.');
      pair.objects = deps.objects.statements; pair.depWarnings = deps.warnings; savePair(pair);
      const notes = [];
      if (deps.objects.statements.length) notes.push(`${deps.objects.statements.length} object(s) to create on the target (${[...new Set(deps.objects.statements.map((x) => x.kind))].join(', ')})`);
      if (deps.missingParents.length) notes.push(`${deps.missingParents.length} FK parent table(s) not selected: ${deps.missingParents.map((m) => m.table).join(', ')}`);
      if (deps.selfRefs.length) notes.push(`self-referencing: ${deps.selfRefs.join(', ')}`);
      if (deps.cycles.length) notes.push(`FK cycles: ${deps.cycles.map((c) => c.join(' <> ')).join('; ')}`);
      pair.depNotes = notes; savePair(pair);
      const skipped = Object.entries(pair.excluded).map(([t, c]) => `${t}.${c.join(',')}`);
      return `${ordered.length} table(s); ${missing.length} to create on the target; load order: ${ordered.join(' > ')}${skipped.length ? `. Not copied (geography/geometry): ${skipped.join('; ')}` : ''}${(pair.depNotes || []).length ? `. ${pair.depNotes.join('. ')}` : ''}`;
    });

    await step(pair, 'Prepare databases', async (s) => {
      const did = [];
      // order: schemas -> alias types -> sequences -> functions -> tables (tables may use them in columns, defaults, computed columns)
      for (const o of pair.objects || []) { await exec(tgt, o.sql); did.push(`${o.kind} ${o.name}`); note(pair, s, 'created ' + did.join('; ')); }
      for (const t of ordered) if (pair.ddl?.[t]) { await exec(tgt, pair.ddl[t]); did.push(`table ${t}`); note(pair, s, 'created ' + did.join('; ')); }
      if (pair.options.disableTargetTriggers) {
        pair.disabledTriggers = pair.disabledTriggers || [];
        for (const x of await userTriggers(tgt, ordered)) {
          await exec(tgt, `DISABLE TRIGGER ${fq(x.schema, x.trigger)} ON ${fq(...x.table.split('.'))}`);
          if (!pair.disabledTriggers.some((d) => d.schema === x.schema && d.trigger === x.trigger)) pair.disabledTriggers.push(x);
          did.push(`disabled trigger ${x.trigger} on target`);
        }
        savePair(pair);
      }
      if (pair.options.enableRcsi) {
        for (const [label, cid] of [['source', src], ['target', tgt]]) {
          try { await exec(cid, 'ALTER DATABASE CURRENT SET READ_COMMITTED_SNAPSHOT ON WITH ROLLBACK IMMEDIATE'); dropPool(cid); did.push(`READ_COMMITTED_SNAPSHOT on ${label}`); }
          catch (e) { did.push(`could not enable READ_COMMITTED_SNAPSHOT on ${label}: ${explain(e)}`); }
        }
      }
      return did.length ? did.join('; ') : { skipped: true, detail: 'nothing to do' };
    });

    await step(pair, 'Start source node', async (s) => {
      writeEngine(pair, 'src');
      note(pair, s, 'engine file written, waiting for SymmetricDS to create its tables (sym-runtime restarts, ~30-60 s)');
      // Ready = default data exists AND SymmetricDS has created the capture triggers on its own config tables.
      // Writing config before that would not be captured/routed, and the node would never create the triggers on the user tables.
      await waitFor(async () => (await q(src, `SELECT (SELECT COUNT(*) FROM sym_channel WHERE channel_id = 'reload') + (SELECT COUNT(*) FROM sym_node WHERE node_id = @n)
          + CASE WHEN (SELECT COUNT(*) FROM sys.triggers WHERE name LIKE 'SYM[_]ON[_]%' AND parent_id IN (OBJECT_ID('sym_trigger'), OBJECT_ID('sym_trigger_router'), OBJECT_ID('sym_router'), OBJECT_ID('sym_channel'))) >= 12 THEN 1 ELSE 0 END AS ok`, { n: ids.src }))[0].ok === 3,
        { timeout: 240000, what: 'the source node to initialise (check: docker compose logs sym-runtime)' });
      await sleep(5000);   // let the startup trigger synchronisation finish
      return 'source node is up';
    });

    await step(pair, 'Load sync configuration', async (s) => {
      await exec(src, configSql(pair, ordered, pair.excluded || {}));
      note(pair, s, 'configuration saved, waiting for SymmetricDS to create the capture triggers');
      const want = ordered.length * 3;
      const t0 = Date.now(); let nudged = false;
      await waitFor(async () => {
        if ((await captureTriggerCount(src, ordered)) >= want) return true;
        // safety net: if SymmetricDS has not noticed the new config after 90 s, touch it once more (captured change => trigger sync)
        if (!nudged && Date.now() - t0 > 90000) { nudged = true; await exec(src, `UPDATE sym_trigger SET last_update_time = GETDATE() WHERE trigger_id LIKE 'sync[_]%'`); }
        return false;
      }, { timeout: 300000, every: 3000, what: `${want} capture triggers (check: docker compose logs sym-runtime)` });
      return `${ordered.length} table(s), ${want} capture triggers`;
    });

    await step(pair, 'Start target node and register', async (s) => {
      writeEngine(pair, 'tgt');   // written only now: registering earlier would run the initial load against an empty config
      note(pair, s, 'target engine file written, waiting for registration (sym-runtime restarts)');
      await waitFor(async () => (await q(src, `SELECT COUNT(*) AS n FROM sym_node_security WHERE node_id = @n AND registration_enabled = 0 AND registration_time IS NOT NULL`, { n: ids.tgt }))[0].n === 1,
        { timeout: 240000, what: 'the target node to register' });
      return 'target registered';
    });

    await step(pair, 'Initial load', async (s) => {
      let last = '';
      await waitFor(async () => {
        const p = await computeParity(src, tgt);
        const done = p.tables.filter((t) => t.match).length;
        last = `${done}/${p.tables.length} tables identical`; note(pair, s, last);
        return p.in_sync;
      }, { timeout: 900000, every: 4000, what: 'source and target to become identical' });
      return `all ${ordered.length} table(s) identical`;
    });

    pair.state = 'running'; pair.error = null; pair.lastAppliedAt = new Date().toISOString(); savePair(pair);
  } catch (e) {
    if (pair.state !== 'error') { pair.state = 'error'; pair.error = explain(e); savePair(pair); }
  }
}

// ---------- actions ----------
export function pause(pair) { removeEngine(pair, 'tgt'); removeEngine(pair, 'src'); pair.state = 'paused'; savePair(pair); }
export function resume(pair) { writeEngine(pair, 'src'); writeEngine(pair, 'tgt'); pair.state = 'running'; savePair(pair); }
export async function reload(pair) {
  const ids = nodeIds(pair);
  await q(pair.sourceConnId, `UPDATE sym_node_security SET initial_load_enabled = 1, initial_load_time = NULL WHERE node_id = @n; SELECT 1 AS ok`, { n: ids.tgt });
}
export async function remove(pair, { uninstall = false } = {}) {
  removeEngine(pair, 'tgt'); removeEngine(pair, 'src');
  const log = [];
  if (uninstall) {
    await sleep(8000);   // let the supervisor stop the engines before dropping their tables
    for (const [label, cid] of [['source', pair.sourceConnId], ['target', pair.targetConnId]]) {
      try {
        await exec(cid, `
          DECLARE @s nvarchar(max) = N'';
          SELECT @s += N'DROP TRIGGER ' + QUOTENAME(SCHEMA_NAME(o.schema_id)) + N'.' + QUOTENAME(t.name) + N';' FROM sys.triggers t JOIN sys.objects o ON o.object_id = t.object_id WHERE t.name LIKE 'SYM[_]ON[_]%';
          SELECT @s += N'ALTER TABLE ' + QUOTENAME(SCHEMA_NAME(schema_id)) + N'.' + QUOTENAME(OBJECT_NAME(parent_object_id)) + N' DROP CONSTRAINT ' + QUOTENAME(name) + N';' FROM sys.foreign_keys WHERE OBJECT_NAME(parent_object_id) LIKE 'sym[_]%';
          SELECT @s += N'DROP TABLE ' + QUOTENAME(SCHEMA_NAME(schema_id)) + N'.' + QUOTENAME(name) + N';' FROM sys.tables WHERE name LIKE 'sym[_]%';
          SELECT @s += N'DROP FUNCTION ' + QUOTENAME(SCHEMA_NAME(schema_id)) + N'.' + QUOTENAME(name) + N';' FROM sys.objects WHERE type IN ('FN','IF','TF') AND name LIKE 'sym[_]%';
          SELECT @s += N'DROP PROCEDURE ' + QUOTENAME(SCHEMA_NAME(schema_id)) + N'.' + QUOTENAME(name) + N';' FROM sys.objects WHERE type = 'P' AND name LIKE 'sym[_]%';
          EXEC (@s);`);
        log.push(`removed SymmetricDS objects from ${label}`);
      } catch (e) { log.push(`could not clean ${label}: ${explain(e)}`); }
    }
    for (const x of pair.disabledTriggers || []) {
      try { await exec(pair.targetConnId, `ENABLE TRIGGER ${fq(x.schema, x.trigger)} ON ${fq(...x.table.split('.'))}`); log.push(`re-enabled trigger ${x.trigger} on target`); } catch (e) { log.push(`could not re-enable ${x.trigger}: ${explain(e)}`); }
    }
  } else log.push('engine stopped; SymmetricDS tables and triggers were left in both databases');
  return log;
}
export function recoverInterrupted() {
  for (const p of listPairs()) if (p.state === 'applying') { p.state = 'error'; p.error = 'Interrupted (the monitor restarted during apply). Press "Retry apply".'; savePair(p); }
}
